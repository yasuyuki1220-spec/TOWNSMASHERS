def spiral(col, c, r0, r1, turns, tube, axis='z', n=28):
    pts = []
    for i in range(n + 1):
        t = i / n; a = turns * 2 * PI * t; r = r0 + (r1 - r0) * t
        pts.append((c[0] + r * math.cos(a), c[1] + r * math.sin(a), c[2]) if axis == 'z' else (c[0] + r * math.cos(a), c[1], c[2] + r * math.sin(a)))
    chain('m', col, pts, tube, tube, 5)

